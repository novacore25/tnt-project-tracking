-- 3. Insert ke archive_campaign_creators dan tampung id yang digenerate
CREATE TEMP TABLE tmp_inserted_cc AS
WITH ins AS (
    INSERT INTO archive_campaign_creators (
        campaign_id, 
        username, 
        nama_asli, 
        link_account, 
        approval, 
        content_type, 
        tier, 
        qty_vt, 
        qty_live, 
        price, 
        created_at
    )
    SELECT 
        t.campaign_id,
        t.username,
        t.username AS nama_asli,
        'https://www.tiktok.com/@' || t.username AS link_account,
        'approved' AS approval,
        'video' AS content_type,
        'nano' AS tier,
        t.qty_vt,
        0 AS qty_live,
        0.00 AS price,
        NOW() AS created_at
    FROM tmp_new_creators t
    RETURNING id, campaign_id, username, qty_vt
)
SELECT id, campaign_id, username, qty_vt FROM ins;

-- 4. Insert baris video placeholder untuk setiap kreator baru (2 atau 3 VT per orang)
INSERT INTO archive_videos (
    campaign_creator_id, 
    urutan, 
    link_video, 
    link_draft, 
    concept, 
    vt_approval, 
    created_at
)
SELECT 
    cc.id,
    s.step AS urutan,
    '' AS link_video,
    NULL AS link_draft,
    NULL AS concept,
    'approved' AS vt_approval,
    NOW() AS created_at
FROM tmp_inserted_cc cc
CROSS JOIN LATERAL generate_series(1, cc.qty_vt) AS s(step);

-- 5. Validasi Guard
DO $$
DECLARE
    v_c260 int; v_c261 int; v_c262 int; v_c263 int; v_c264 int; v_c265 int; v_c269 int;
    v_total_ins int;
    v_total_vids int;
BEGIN
    SELECT COUNT(*) INTO v_total_ins FROM tmp_inserted_cc;
    IF v_total_ins != 807 THEN
        RAISE EXCEPTION 'Guard gagal: total inserted cc adalah %, bukan 807', v_total_ins;
    END IF;

    SELECT COUNT(*) INTO v_c260 FROM archive_campaign_creators WHERE campaign_id = 260;
    SELECT COUNT(*) INTO v_c261 FROM archive_campaign_creators WHERE campaign_id = 261;
    SELECT COUNT(*) INTO v_c262 FROM archive_campaign_creators WHERE campaign_id = 262;
    SELECT COUNT(*) INTO v_c263 FROM archive_campaign_creators WHERE campaign_id = 263;
    SELECT COUNT(*) INTO v_c264 FROM archive_campaign_creators WHERE campaign_id = 264;
    SELECT COUNT(*) INTO v_c265 FROM archive_campaign_creators WHERE campaign_id = 265;
    SELECT COUNT(*) INTO v_c269 FROM archive_campaign_creators WHERE campaign_id = 269;

    IF v_c260 != 374 OR v_c261 != 437 OR v_c262 != 157 OR v_c263 != 169 OR v_c264 != 238 OR v_c265 != 183 OR v_c269 != 345 THEN
        RAISE EXCEPTION 'Guard gagal: total kreator tidak cocok target! (260=%, 261=%, 262=%, 263=%, 264=%, 265=%, 269=%)',
            v_c260, v_c261, v_c262, v_c263, v_c264, v_c265, v_c269;
    END IF;

    SELECT COUNT(*) INTO v_total_vids
    FROM archive_videos v
    JOIN tmp_inserted_cc cc ON v.campaign_creator_id = cc.id;

    RAISE NOTICE 'Sukses: 807 kreator baru berhasil ditambahkan dengan total % video baru!', v_total_vids;
    RAISE NOTICE 'Target tercapai: OMG2=374, OMG3=437, Wardah1=157, Wardah2=169, Wardah3=238, Wardah4=183, PWS2=345';
END $$;

